// Extracts the Swift multi-line string literals from WebAdminContent.swift
// (xcf-chat-main/Sources/MultiPeerChatCore/WebAdminContent.swift) into
// src/admin-content.js so the Worker serves byte-identical admin pages.
//
// Usage: node scripts/extract-admin-content.mjs [path/to/WebAdminContent.swift]
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const src = process.argv[2] ||
  join(here, '../../xcf-chat-main/Sources/MultiPeerChatCore/WebAdminContent.swift');
const swift = readFileSync(src, 'utf8');

// Swift string escape handling (SE-0168 multi-line literals)
function unescapeSwift(body) {
  let out = '';
  for (let i = 0; i < body.length; i++) {
    const c = body[i];
    if (c !== '\\') { out += c; continue; }
    const n = body[++i];
    switch (n) {
      case 'n': out += '\n'; break;
      case 't': out += '\t'; break;
      case 'r': out += '\r'; break;
      case '0': out += '\0'; break;
      case '\\': out += '\\'; break;
      case '"': out += '"'; break;
      case "'": out += "'"; break;
      case '\n': break; // line continuation
      case 'u': {
        const close = body.indexOf('}', i);
        out += String.fromCodePoint(parseInt(body.slice(i + 2, close), 16));
        i = close;
        break;
      }
      default: throw new Error(`Unsupported escape \\${n}`);
    }
  }
  return out;
}

function literal(content) {
  // content = text between opening `"""\n` and closing `"""` (incl. its indentation)
  const lines = content.split('\n');
  const closingIndent = lines.pop(); // whitespace before closing """
  const stripped = lines.map(l => (l.startsWith(closingIndent) ? l.slice(closingIndent.length) : l.trimStart()));
  return unescapeSwift(stripped.join('\n'));
}

const re = /public static func (\w+)\(\) -> String \{\s*return """\n([\s\S]*?)"""/g;
const exports = [];
let m;
while ((m = re.exec(swift))) {
  exports.push(`export const ${m[1]} = ${JSON.stringify(literal(m[2]))};`);
}
if (exports.length !== 5) throw new Error(`Expected 5 admin literals, found ${exports.length}`);

const out = `// AUTO-GENERATED by scripts/extract-admin-content.mjs from WebAdminContent.swift. Do not edit.\n${exports.join('\n\n')}\n`;
writeFileSync(join(here, '../src/admin-content.js'), out);
console.log(`Wrote src/admin-content.js (${exports.length} exports)`);
